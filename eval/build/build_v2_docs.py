"""Generate `eval/datasets/vault_eval_v2/documents.yaml`: the v2 document map and the split lists (S21.10a).

$0, no model calls. Maps every document key the v2 items mention (`source_doc`, `doc_ids`,
`gold_evidence.doc`) to its file:

- `authored`: fixtures in `vault_eval_v2/docs` (keys and titles in `docs/manifest.yaml`).
- `v1`: the v1 documents (`vault_eval_v1/documents.yaml`; its `eval/sources/...` files stay third-party).
- `public`: FinanceBench / QASPER / CUAD documents of strata 1-6. The key is inverted to the source reference
  the sampler used (`fb:<doc_name>`, `qasper:<arxiv id>`, `cuad:<title>`). The PDF is the local source when
  present, else the sampler's cache location (`eval/sources/_v2_cache/pdfs/...`); `--download` fetches the
  missing ones (network, $0).
- `virtual`: a cluster key with no file (e.g. `vault` for whole-vault items). Never uploaded.

Paths under `eval/sources/` are resolved at run time against `VAULT_EVAL_SOURCES` (default
`<repo>/eval/sources`), so a worktree reads the main checkout's sources.

Regenerate:

    VAULT_EVAL_SOURCES=/path/to/main/eval/sources \\
        python eval/build/build_v2_docs.py [--download] [--check]

`--check` exits 1 when the committed file differs from the regenerated one (CI-safe, offline).

Also provides the run-time helpers: `load_documents_v2`, `resolve_file`, `missing_files`, `document_units`
(the document sentence stream gold ranges index; `eval.run_v2` maps ranges to chunk sentences with it).
"""

from __future__ import annotations

import argparse
import hashlib
import os
import pathlib
import sys
from collections.abc import Iterable, Mapping, Sequence
from typing import Any

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
for _p in (str(ROOT), str(ROOT / "backend")):
    if _p not in sys.path:
        sys.path.insert(0, _p)

from eval.loader import DATASET_V2_DIR, load_dataset_v2  # noqa: E402
from eval.schema import GoldItemV2  # noqa: E402
from eval.splits_v2 import SPLITS_V2, live_items, split_of  # noqa: E402

DOCS_YAML = DATASET_V2_DIR / "documents.yaml"
V1_DOCS_YAML = ROOT / "eval" / "datasets" / "vault_eval_v1" / "documents.yaml"
MANIFEST = DATASET_V2_DIR / "docs" / "manifest.yaml"
SOURCES_PREFIX = "eval/sources/"
HEADER = (
    "# Generated by eval/build/build_v2_docs.py (S21.10a). Do not edit by hand.\n"
    "# Regenerate: VAULT_EVAL_SOURCES=<main checkout>/eval/sources python eval/build/build_v2_docs.py\n"
)


def sources_dir() -> pathlib.Path:
    return pathlib.Path(os.environ.get("VAULT_EVAL_SOURCES", ROOT / "eval" / "sources"))


def cache_dir() -> pathlib.Path:
    return pathlib.Path(os.environ.get("VAULT_EVAL_CACHE", sources_dir() / "_v2_cache"))


def resolve_file(file: str) -> pathlib.Path:
    """A map entry's `file` as a local path (`eval/sources/...` follows `VAULT_EVAL_SOURCES`)."""
    if file.startswith(SOURCES_PREFIX):
        return sources_dir() / file[len(SOURCES_PREFIX) :]
    return ROOT / file


def _rel_sources(p: pathlib.Path) -> str:
    """`p` as `eval/sources/...` when it lives under the sources directory, else relative to the repo."""
    src = sources_dir()
    try:
        return SOURCES_PREFIX + p.relative_to(src).as_posix()
    except ValueError:
        return p.relative_to(ROOT).as_posix()


# --- which documents the items mention ---------------------------------------------------------------------


def item_docs(item: GoldItemV2) -> set[str]:
    """Documents an item may read: scope, gold evidence, and its `source_doc` (when that is a document)."""
    out = set(item.doc_ids or ())
    out |= {g.doc for g in item.gold_evidence}
    out.add(item.source_doc)
    return out


def all_doc_keys(items: Iterable[GoldItemV2]) -> set[str]:
    return {d for i in items for d in item_docs(i)}


# --- key -> source reference ------------------------------------------------------------------------------


class _Public:
    """Inverts the sampler's keys (`sample_public.py`: fb_<slug>, qasper_<id>, cuad_<slug>_<sha6>)."""

    def __init__(self) -> None:
        from eval.build import sample_public as sp

        self.sp = sp
        src = sources_dir()
        self.fb: dict[str, str] = {}
        for f in ("fb_docs.jsonl", "fb_questions.jsonl"):
            p = src / f
            if p.exists():
                import json

                for line in p.read_text().splitlines():
                    name = json.loads(line)["doc_name"]
                    self.fb[f"fb_{sp.slug(name)}"] = name
        self.cuad: dict[str, str] = {}
        root = src / "cuad_full"
        if root.exists():
            for p in root.rglob("*"):
                if p.suffix.lower() == ".pdf":
                    t = p.stem
                    sha6 = hashlib.sha1(t.encode()).hexdigest()[:6]  # noqa: S324
                    self.cuad[f"cuad_{sp.slug(t, 40)}_{sha6}"] = t

    def ref(self, key: str) -> str | None:
        if key in self.fb:
            return f"fb:{self.fb[key]}"
        if key in self.cuad:
            return f"cuad:{self.cuad[key]}"
        if key.startswith("qasper_") and key.count("_") == 2:
            return "qasper:" + key.removeprefix("qasper_").replace("_", ".")
        return None

    def path(self, ref: str) -> pathlib.Path:
        """Where the PDF is, or will be after `--download` (the sampler's cache layout)."""
        kind, _, ident = ref.partition(":")
        src, cache = sources_dir(), cache_dir()
        if kind == "fb":
            local = src / "fb_pdfs" / f"{ident}.pdf"
            return local if local.exists() else cache / "pdfs" / "fb" / f"{ident}.pdf"
        if kind == "qasper":
            local = src / "qasper_pdfs" / f"{ident}.pdf"
            return local if local.exists() else cache / "pdfs" / "qasper" / f"{ident}.pdf"
        for p in (src / "cuad_full").rglob("*"):
            if p.suffix.lower() == ".pdf" and p.stem == ident:
                return p
        raise FileNotFoundError(ref)

    def download(self, ref: str) -> pathlib.Path:
        return self.sp.Sources(sources_dir(), cache_dir()).resolve(ref)


def _sha(p: pathlib.Path) -> str | None:
    return hashlib.sha256(p.read_bytes()).hexdigest() if p.is_file() else None


def build_map(items: Sequence[GoldItemV2], *, download: bool = False) -> dict[str, dict[str, Any]]:
    keys = sorted(all_doc_keys(items))
    manifest: dict[str, Any] = yaml.safe_load(MANIFEST.read_text())["documents"]
    v1: dict[str, Any] = yaml.safe_load(V1_DOCS_YAML.read_text())["documents"]
    pub: _Public | None = None
    out: dict[str, dict[str, Any]] = {}
    for k in keys:
        if k in manifest:
            rel = (DATASET_V2_DIR / "docs" / manifest[k]["file"]).relative_to(ROOT).as_posix()
            e: dict[str, Any] = {"kind": "authored", "file": rel, "title": manifest[k].get("title")}
        elif k in v1:
            e = {"kind": "v1", "file": v1[k]["file"], "title": v1[k].get("title")}
        else:
            pub = pub or _Public()
            ref = pub.ref(k)
            if ref is None:
                out[k] = {"kind": "virtual"}
                continue
            try:
                p = pub.download(ref) if download else pub.path(ref)
            except FileNotFoundError:
                p = cache_dir() / "pdfs" / ref.replace(":", "/")
            except Exception as ex:  # a failed download must not hide the others
                print(f"download failed for {ref}: {type(ex).__name__}: {ex}", file=sys.stderr)
                p = cache_dir() / "pdfs" / ref.replace(":", "/")
            e = {"kind": "public", "ref": ref, "file": _rel_sources(p)}
        sha = _sha(resolve_file(e["file"]))
        old = _OLD_SHA.get(k)
        e["sha256"] = sha or old  # keep the committed hash when this machine lacks the file
        out[k] = e
    return out


_OLD_SHA: dict[str, str | None] = {}


def build_splits(items: Sequence[GoldItemV2], docs: Mapping[str, Mapping[str, Any]]) -> dict[str, Any]:
    live = live_items(items)
    out: dict[str, Any] = {}
    for s in SPLITS_V2:
        sub = [i for i in live if split_of(i.source_doc) == s]
        need = sorted(d for d in all_doc_keys(sub) if docs.get(d, {}).get("kind") not in (None, "virtual"))
        out[s] = {
            "items": len(sub),
            "source_docs": sorted({i.source_doc for i in sub}),
            "documents": need,
        }
    return out


def render(items: Sequence[GoldItemV2], *, download: bool = False) -> str:
    docs = build_map(items, download=download)
    body = {
        "ingest": {
            "mode": "light",
            "note": "wait for status ready (parse, chunk, embed); never wait for enriched (brief). The API "
            "has no per-upload switch: set BRIEF_MAX_USD small on the worker to cap brief spend",
        },
        "documents": docs,
        "splits": build_splits(items, docs),
    }
    return HEADER + yaml.safe_dump(body, sort_keys=False, allow_unicode=True, width=110)


# --- run-time helpers -------------------------------------------------------------------------------------


def load_documents_v2(path: pathlib.Path = DOCS_YAML) -> dict[str, dict[str, Any]]:
    return dict(yaml.safe_load(path.read_text())["documents"])


def missing_files(keys: Iterable[str], docs: Mapping[str, Mapping[str, Any]]) -> dict[str, str]:
    """key -> reason for every uploadable document whose file is absent or unknown to the map."""
    out: dict[str, str] = {}
    for k in sorted(set(keys)):
        e = docs.get(k)
        if e is None:
            out[k] = "not in documents.yaml (regenerate: make eval-v2-docs)"
        elif e["kind"] == "virtual":
            continue
        elif not resolve_file(e["file"]).is_file():
            out[k] = f"missing {e['file']} (make eval-v2-docs ARGS=--download)"
    return out


def document_units(key: str, entry: Mapping[str, Any]) -> list[str] | None:
    """The document sentence stream gold ranges index (None for a virtual key). Authored fixtures use the
    fixture convention; PDFs use the parsed-document cache of the sampler, building it when absent."""
    if entry["kind"] == "virtual":
        return None
    path = resolve_file(entry["file"])
    if path.suffix.lower() == ".pdf":
        from eval.build import sample_public as sp

        return list(sp.load_stream(path, cache_dir() / "streams", build=True).texts)
    from eval.build.check_coverage import fixture_sentences

    return fixture_sentences(path)


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="build_v2_docs")
    ap.add_argument("--download", action="store_true", help="fetch missing public PDFs (network, $0)")
    ap.add_argument("--check", action="store_true", help="exit 1 when documents.yaml is not up to date")
    ap.add_argument("--out", type=pathlib.Path, default=DOCS_YAML)
    a = ap.parse_args(argv)
    if a.out.exists():
        _OLD_SHA.update({k: v.get("sha256") for k, v in load_documents_v2(a.out).items()})
    items = load_dataset_v2().items
    text = render(items, download=a.download)
    docs = yaml.safe_load(text)["documents"]
    miss = missing_files(docs, docs)
    kinds = {
        k: sum(1 for d in docs.values() if d["kind"] == k) for k in ("authored", "v1", "public", "virtual")
    }
    print(f"documents {len(docs)} {kinds}; files missing on this machine: {len(miss)}")
    if a.check:
        if not a.out.exists() or a.out.read_text() != text:
            print(f"{a.out} is out of date; run make eval-v2-docs")
            return 1
        return 0
    a.out.write_text(text)
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
